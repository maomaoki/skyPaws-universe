/**
 * 工具执行状态：描述“这一次 tool_call 是否兑现了工具契约”，
 * 不描述数据是否完整——读取被截断仍属于 ok，由 hint + metadata 说明后续。
 */

export type ToolStatus =
  /** 完成了承诺的事（可能只是返回了一部分数据，例如窗口读取被截断） */
  | "ok"
  /** 执行了但失败：参数错、路径越界、IO 异常等，模型可据 code 改道 */
  | "error"
  /** 用户拒绝，工具根本没有执行；不允许重试同一操作 */
  | "denied"
  /** 用户 Ctrl+C 中止，工具根本没有执行；内核应停止循环 */
  | "aborted";
